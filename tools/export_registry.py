#!/usr/bin/env python3
"""Export original MCP block/item/biome getters to a native constexpr registry.

No values are inferred from wiki tables. Java is used only while regenerating
the header; the C++ application has no JVM dependency.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys


def run(arguments: list[str], cwd: Path) -> None:
    result = subprocess.run(arguments, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if result.returncode:
        raise RuntimeError(result.stdout)


def javac(arguments: list[str], build: Path) -> None:
    # An argument file avoids Windows command-line limits for the original Java
    # source list. Paths are quoted by javac's own grammar, without a shell.
    argfile = build / "javac_registry.args"
    argfile.write_text("\n".join('"' + arg.replace("\\", "/").replace('"', '\\"') + '"' for arg in arguments), encoding="utf-8")
    run(["javac", "@" + str(argfile)], build)


def cpp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def cpp_float(value: float) -> str:
    result = format(value, ".9g")
    if "." not in result and "e" not in result:
        result += ".0"
    return result + "f"


def cpp_bool(value: bool) -> str:
    return "true" if value else "false"


def header(data: dict, output: Path) -> tuple[int, int, int]:
    rules = [([1.0] * 198, [False] * 198)]
    rule_lookup = {(tuple(rules[0][0]), tuple(rules[0][1])): 0}
    foods = [([0] * 16, [0.0] * 16)]
    for item in data["items"]:
        key = (tuple(item["strength"]), tuple(item["harvest"]))
        if key not in rule_lookup:
            rule_lookup[key] = len(rules)
            rules.append((item["strength"], item["harvest"]))
        item["toolRule"] = rule_lookup[key]
        item["foodRule"] = 0
        if item["food"] and any(f["healAmount"] != item["healAmount"] or f["saturationModifier"] != item["saturationModifier"] for f in item["foodVariants"]):
            item["foodRule"] = len(foods)
            foods.append(([f["healAmount"] for f in item["foodVariants"]], [f["saturationModifier"] for f in item["foodVariants"]]))
    lines = ["#pragma once", "// Generated by tools/export_registry.py from original MCP getters. Do not edit.",
             "// Include mc/registry.hpp, which declares these records, rather than this file directly.",
             "namespace mc::registry::detail {", "inline constexpr std::array<BlockInfo, 198> blocks{{"]
    for block in data["blocks"]:
        fields = ["true", cpp_string(block["name"]), cpp_string(block["kind"]), cpp_string(block["material"]),
                  cpp_float(block["hardness"]), cpp_bool(block["toolRequired"]),
                  str(block["replaceableMask"]), str(block["validMetadataMask"])]
        fields += [cpp_string(block[name]) for name in ["stepSound", "breakSound", "placeSound"]]
        fields += [cpp_float(block[name]) for name in ["soundVolume", "soundPitch", "slipperiness"]]
        fields += [str(block["lightOpacity"])]
        fields += [cpp_bool(block[name]) for name in ["fullCube", "normalCube", "fullBlock", "materialOpaque", "materialBlocksMovement", "materialSolid"]]
        lines.append("    {" + ", ".join(fields) + "}, // " + str(block["id"]))
    lines += ["}};", "inline constexpr auto items = []() constexpr {",
              f"    std::array<ItemInfo, {max(item['id'] for item in data['items']) + 1}> result{{}};"]
    for item in data["items"]:
        fields = ["true", cpp_string(item["name"]), cpp_string(item["kind"])]
        fields += [str(item[name]) for name in ["maxStack", "maxDamage", "useDuration", "useAction"]]
        fields += [cpp_bool(item["hasSubtypes"]), str(item["armorSlot"]), str(item["blockId"]),
                   cpp_bool(item["food"]), cpp_bool(item["alwaysEdible"]), str(item["healAmount"]),
                   cpp_float(item["saturationModifier"]), repr(float(item["attackDamage"])), str(item["toolRule"]), str(item["foodRule"])]
        lines.append(f"    result[{item['id']}] = {{" + ", ".join(fields) + "};")
    lines += ["    return result;", "}();", f"inline constexpr std::array<ToolRule, {len(rules)}> tools{{{{"]
    for strength, harvest in rules:
        lines.append("    {{{" + ", ".join(cpp_float(x) for x in strength) + "}}, {{" + ", ".join(cpp_bool(x) for x in harvest) + "}}},")
    lines += ["}};", f"inline constexpr std::array<FoodRule, {len(foods)}> foods{{{{"]
    for heal, saturation in foods:
        lines.append("    {{{" + ", ".join(str(x) for x in heal) + "}}, {{" + ", ".join(cpp_float(x) for x in saturation) + "}}},")
    lines += ["}};", "inline constexpr auto biomes = []() constexpr {", "    std::array<BiomeInfo, 256> result{};"]
    for biome in data["biomes"]:
        fields = ["true", cpp_string(biome["name"]), cpp_float(biome["temperature"]), cpp_float(biome["rainfall"]),
                  str(biome["grassColor"]), str(biome["foliageColor"]), str(biome["waterColor"]), cpp_bool(biome["snow"])]
        lines.append(f"    result[{biome['id']}] = {{" + ", ".join(fields) + "};")
    lines += ["    return result;", "}();", "} // namespace mc::registry::detail", ""]
    output.write_text("\n".join(lines), encoding="ascii")
    return len(data["items"]), len(rules), len(data["biomes"])


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mcp", type=Path, default=root.parent / "MCP-919-main")
    args = parser.parse_args()
    mcp = args.mcp.resolve()
    build = root / "build/registry_export"
    classes = build / "classes"
    classes.mkdir(parents=True, exist_ok=True)
    classpath = os.pathsep.join(str(p) for p in [classes, mcp / "bin/minecraft", mcp / "jars/versions/1.8.9/1.8.9.jar",
                                               *sorted((mcp / "jars/libraries").rglob("*.jar"))])
    source = mcp / "src/minecraft/net/minecraft"
    sources = []
    for subtree in ["block", "item", "world/biome"]:
        sources.extend(sorted((source / subtree).rglob("*.java")))
    sources += [source / "init/Bootstrap.java", source / "world/ColorizerGrass.java", source / "world/ColorizerFoliage.java"]
    print(f"Compiling {len(sources)} original registry, item, block and biome sources...", flush=True)
    javac(["-encoding", "UTF-8", "--release", "8", "-cp", classpath, "-d", str(classes), *map(str, sources)], build)
    javac(["-encoding", "UTF-8", "-cp", classpath, "-d", str(classes), str(root / "tests/java/RegistryExport.java")], build)
    raw = build / "registry.json"
    run(["java", "-Djava.awt.headless=true", "-cp", classpath, "RegistryExport", str(raw)], build)
    data = json.loads(raw.read_text(encoding="utf-8"))
    output = root / "include/mc/registry_data.hpp"
    item_count, tool_rules, biome_count = header(data, output)
    report = {"source": "actual MCP getter results from newly compiled original Java sources", "blocks": len(data["blocks"]),
              "items": item_count, "deduplicated_tool_rules": tool_rules, "biomes": biome_count,
              "biome_sample_position": [0, 64, 0], "header_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
              "source_sha256": {str(path.relative_to(mcp)): hashlib.sha256(path.read_bytes()).hexdigest() for path in sources}}
    (build / "report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(f"Exported {len(data['blocks'])} blocks, {item_count} items, {tool_rules} tool rules and {biome_count} biomes to {output}")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"Registry export failed: {error}", file=sys.stderr)
        sys.exit(1)
