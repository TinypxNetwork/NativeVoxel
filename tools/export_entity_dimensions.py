#!/usr/bin/env python3
"""Export vanilla entity target-box base dimensions from actual spawn constructors."""
from __future__ import annotations
import argparse
import hashlib
import json
import os
import struct
from pathlib import Path
import sys
from export_registry import javac,cpp_float,cpp_string
from verify_physics import make_reference,run


def main()->None:
    root=Path(__file__).resolve().parents[1];parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mcp",type=Path,default=root.parent/"MCP-919-main")
    parser.add_argument("--cxx",default="D:/Strawberry/c/bin/g++.exe" if os.name=="nt" else "g++")
    args=parser.parse_args();mcp=args.mcp.resolve()
    build=root/"build/entity_dimensions";build.mkdir(parents=True,exist_ok=True);make_reference(root,mcp,build)
    cp=os.pathsep.join(str(p) for p in [build,mcp/"bin/minecraft",mcp/"jars/versions/1.8.9/1.8.9.jar",*sorted((mcp/"jars/libraries").rglob("*.jar"))])
    source=mcp/"src/minecraft/net/minecraft/entity"
    sources=list(source.glob("*.java"))
    for folder in ["boss","monster","passive","item","projectile"]:sources.extend((source/folder).glob("*.java"))
    sources.append(source/"player/EntityPlayer.java")
    print(f"Compiling {len(sources)} original entity sources...",flush=True)
    javac(["-encoding","UTF-8","--release","8","-cp",cp,"-d",str(build),*map(str,sorted(sources)),str(build/"PhysicsReference.java"),str(root/"tests/java/EntityDimensionsExport.java")],build)
    raw=build/"entity_dimensions.json";run(["java","-Djava.awt.headless=true","-cp",cp,"EntityDimensionsExport",str(raw)],build)
    rows=json.loads(raw.read_text());out=["#pragma once","// Generated by tools/export_entity_dimensions.py from original vanilla spawn constructors.",
        "namespace mc {","struct EntityDimensions {", "    bool valid{}; float width{},height{},collisionBorder{.1f};",
        "    bool collidable{},customBounds{},multipart{}; const char* className{\"\"};","};",
        "// kind 0=player, 1=mob protocol type, 2=object protocol type.",
        "// Adult, slime-size-1 base. Apply packet metadata before using the box.",
        "// customBounds marks hanging entities; width/height alone do not encode their oriented AABB.",
        "inline constexpr EntityDimensions entityDimensions(int kind,int type) {",
        "    switch(kind) {"]
    for kind in range(3):
        values=[r for r in rows if r["kind"]==kind]
        out.append(f"    case {kind}:")
        if kind:out.append("        switch(type) {")
        for row in values:
            fields=["true",cpp_float(row["width"]),cpp_float(row["height"]),cpp_float(row["collisionBorder"]),str(row["collidable"]).lower(),str(row["customBounds"]).lower(),str(row["multipart"]).lower(),cpp_string(row["className"])]
            if kind:out.append(f"        case {row['type']}: return {{"+",".join(fields)+"};")
            else:out.append("        return {"+",".join(fields)+"};")
        if kind:out.extend(["        default: return {};","        }"])
    out.extend(["    default: return {};","    }","}","} // namespace mc",""])
    output=root/"include/mc/entity_dimensions.hpp";output.write_text("\n".join(out),encoding="ascii")
    executable=build/("entity_dimensions_tests.exe" if os.name=="nt" else "entity_dimensions_tests")
    run([args.cxx,"-std=c++17","-O2","-Wall","-Wextra","-I",str(root/"include"),str(root/"tests/entity_dimensions_tests.cpp"),"-o",str(executable)],root)
    run([str(executable)],root)
    actual={}
    for line in run([str(executable),"--dump"],root).stdout.splitlines():
        v=list(map(int,line.split()));actual[tuple(v[:2])]=v[2:]
    for row in rows:
        expected=[struct.unpack("<I",struct.pack("<f",row[name]))[0] for name in ["width","height","collisionBorder"]]+[int(row[name]) for name in ["collidable","customBounds","multipart"]]
        if actual[(row["kind"],row["type"])]!=expected:raise RuntimeError(f"compiled dimensions differ from Java for {row}")
    report={"records":len(rows),"mob_types":sum(r["kind"]==1 for r in rows),"object_types":sum(r["kind"]==2 for r in rows),"native_bitwise_match":True,
        "source_sha256":{str(p.relative_to(mcp)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(sources)},"header_sha256":hashlib.sha256(output.read_bytes()).hexdigest()}
    (build/"report.json").write_text(json.dumps(report,indent=2),encoding="utf-8")
    print(f"Exported {len(rows)} original entity hitbox records to {output}")


if __name__=="__main__":
    try:main()
    except Exception as error:print(f"Entity dimensions export failed: {error}",file=sys.stderr);sys.exit(1)
