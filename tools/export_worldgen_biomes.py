#!/usr/bin/env python3
"""Export the original biome types/heights/state fields for native generation."""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import sys
from export_registry import javac,cpp_float,cpp_string
from verify_physics import run


def class_name(name):return name.rsplit(".",1)[-1].replace("$","_")
def main()->None:
    root=Path(__file__).resolve().parents[1];parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("--mcp",type=Path,default=root.parent/"MCP-919-main")
    args=parser.parse_args();mcp=args.mcp.resolve();build=root/"build/worldgen_reference";build.mkdir(parents=True,exist_ok=True)
    cp=os.pathsep.join(str(p) for p in [build,mcp/"bin/minecraft",mcp/"jars/versions/1.8.9/1.8.9.jar",*sorted((mcp/"jars/libraries").rglob("*.jar"))])
    source=mcp/"src/minecraft/net/minecraft/world/biome"
    javac(["-encoding","UTF-8","--release","8","-cp",cp,"-d",str(build),*map(str,sorted(source.glob("*.java"))),str(root/"tests/java/WorldgenBiomeExport.java")],build)
    raw=build/"biome_data.json";run(["java","-cp",cp,"WorldgenBiomeExport",str(raw)],build);data=json.loads(raw.read_text())
    classes=sorted(set(class_name(b["class"]) for b in data["biomes"]))
    out=["#pragma once","// Generated by tools/export_worldgen_biomes.py from original BiomeGenBase instances.","#include <array>","#include <cstdint>","namespace mc::worldgen {",
         "enum class BiomeClass { Unknown,"+",".join(classes)+" };","enum class TemperatureCategory { OCEAN,COLD,MEDIUM,WARM };",
         "struct BiomeDescription { bool valid{}; int biomeID{}; const char* name{\"\"}; BiomeClass kind{BiomeClass::Unknown}; TemperatureCategory category{TemperatureCategory::MEDIUM};",
         "    bool snow{},mesa{}; float height{},variation{},temperature{},rainfall{}; std::uint16_t top{},filler{}; int surfaceDelegate{-1}; const char* surfaceClass{\"\"}; int terrainVariant{}; bool mesaBryce{},mesaForest{};",
         "    BiomeClass getBiomeClass() const {return kind;} TemperatureCategory getTempCategory() const {return category;} bool isSnowyBiome() const {return snow;}",
         "    bool isEqualTo(const BiomeDescription* other) const {return other&&kind==other->kind;}","};","namespace biome_ids {"]
    for name,id in sorted(data["ids"].items()):out.append(f"inline constexpr int {name}={id};")
    out += ["}","inline constexpr auto biomeDescriptions=[]() constexpr {std::array<BiomeDescription,256> result{};"]
    for b in data["biomes"]:
        values=["true",str(b["id"]),cpp_string(b["name"]),"BiomeClass::"+class_name(b["class"]),"TemperatureCategory::"+b["category"],str(b["snow"]).lower(),str(b["mesa"]).lower(),
                *[cpp_float(b[n]) for n in ["height","variation","temperature","rainfall"]],str(b["top"]),str(b["filler"]),str(b["delegate"]),cpp_string(class_name(b["surfaceClass"])),
                str(b["fields"].get("field_150638_aH",b["fields"].get("field_150644_aH",0))),str(b["fields"].get("field_150626_aH",False)).lower(),str(b["fields"].get("field_150620_aI",False)).lower()]
        out.append(f"    result[{b['id']}]={{"+",".join(values)+"};")
    out += ["    return result;}();","inline const BiomeDescription* biomeDefinition(int id) {if(id<0||id>=256)return &biomeDescriptions[0];return biomeDescriptions[id].valid?&biomeDescriptions[id]:nullptr;}","} // namespace mc::worldgen",""]
    (root/"include/mc/worldgen_biome_data.hpp").write_text("\n".join(out),encoding="ascii")
    rules=sorted({class_name(b[field]) for b in data['biomes'] for field in ['decorateClass','treeClass','flowerClass','grassClass']})
    counts=['waterlilyPerChunk','treesPerChunk','flowersPerChunk','grassPerChunk','deadBushPerChunk','mushroomsPerChunk','reedsPerChunk','cactiPerChunk','sandPerChunk','sandPerChunk2','clayPerChunk','bigMushroomsPerChunk']
    out=['#pragma once','// Generated from original biome instances by tools/export_worldgen_biomes.py.','#include <array>','namespace mc::worldgen {',
         'enum class BiomeRule { Unknown,'+','.join(rules)+' };',
         'struct DecorationDescription { bool valid{}; int delegate{-1}; BiomeRule decorate{},trees{},flowers{},grass{}; int variant{}; bool sunflowers{},iceSpikes{},jungleEdge{};',
         '    int '+','.join(name+'{}' for name in counts)+'; bool springs{}; };',
         'inline constexpr auto decorationDescriptions=[]() constexpr {std::array<DecorationDescription,256> result{};']
    for b in data['biomes']:
        fields=b['fields'];values=['true',str(b['delegate']),*['BiomeRule::'+class_name(b[field]) for field in ['decorateClass','treeClass','flowerClass','grassClass']],
            str(fields.get('field_150632_aF',fields.get('field_150644_aH',fields.get('field_150638_aH',0)))),
            *[str(fields.get(field,False)).lower() for field in ['field_150628_aC','field_150615_aC','field_150614_aC']],
            *[str(b['decoration'][name]) for name in counts],str(b['decoration']['generateLakes']).lower()]
        out.append(f"    result[{b['id']}]={{"+','.join(values)+'};')
    out+=['    return result;}();','} // namespace mc::worldgen','']
    (root/'include/mc/worldgen_decoration_data.hpp').write_text('\n'.join(out),encoding='ascii')
    print(f"Exported {len(data['biomes'])} original biome descriptors and {len(classes)} comparable classes")


if __name__=="__main__":
    try:main()
    except Exception as error:print(f"Worldgen biome export failed: {error}",file=sys.stderr);sys.exit(1)
