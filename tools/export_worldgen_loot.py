#!/usr/bin/env python3
"""Export vanilla book-enchantment availability; reuse crafting weights/compatibility."""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import sys
from export_registry import javac
from verify_physics import run

def main()->None:
    root=Path(__file__).resolve().parents[1];parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--mcp',type=Path,default=root.parent/'MCP-919-main');args=parser.parse_args();mcp=args.mcp.resolve();build=root/'build/worldgen_reference';build.mkdir(parents=True,exist_ok=True)
    cp=os.pathsep.join(str(p) for p in [build,mcp/'bin/minecraft',mcp/'jars/versions/1.8.9/1.8.9.jar',*sorted((mcp/'jars/libraries').rglob('*.jar'))]);sources=sorted((mcp/'src/minecraft/net/minecraft/enchantment').glob('*.java'))
    javac(['-encoding','UTF-8','--release','8','-cp',cp,'-d',str(build),*map(str,sources),str(root/'tests/java/WorldgenLootExport.java')],build)
    raw=build/'loot_data.json';run(['java','-cp',cp,'WorldgenLootExport',str(raw)],build);data=json.loads(raw.read_text());rules=data['rules'];maxLevels=max(len(rule['levels']) for rule in rules)
    out=['#pragma once','// Generated by tools/export_worldgen_loot.py from original Enchantment getters.','#include <array>','namespace mc::worldgen::lootdata {',
         'struct Level {int level{},minimum{},maximum{};};',f'struct Rule {{int id{{}};std::array<Level,{maxLevels}> levels{{}};}};',
         f'inline constexpr int bookEnchantability={data["bookEnchantability"]};',f'inline constexpr std::array<Rule,{len(rules)}> bookRules{{{{']
    for rule in rules:out.append('    {'+str(rule['id'])+',{{'+','.join('{'+','.join(map(str,level))+'}' for level in rule['levels'])+'}}},')
    out+=['}};','} // namespace mc::worldgen::lootdata',''];(root/'include/mc/worldgen_loot_data.hpp').write_text('\n'.join(out),encoding='ascii');print(f'Exported availability ranges for {len(rules)} original book enchantments')

if __name__=='__main__':
    try:main()
    except Exception as error:print(f'Loot export failed: {error}',file=sys.stderr);sys.exit(1)
