#!/usr/bin/env python3
"""Export static brewing rules from original MCP classes (development only)."""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess

def run(args:list[str],cwd:Path):
    result=subprocess.run(args,cwd=cwd,capture_output=True,text=True)
    if result.returncode:raise RuntimeError(result.stdout+result.stderr)

def main():
    root=Path(__file__).resolve().parents[1];parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("--mcp",type=Path,default=root.parent/"MCP-919-main");args=parser.parse_args();mcp=args.mcp.resolve();build=root/"build/simulation_export";classes=build/"classes";classes.mkdir(parents=True,exist_ok=True)
    classpath=os.pathsep.join(map(str,[classes,root/"build/crafting_export/classes",root/"build/registry_export/classes",mcp/"bin/minecraft",mcp/"jars/versions/1.8.9/1.8.9.jar",*sorted((mcp/"jars/libraries").rglob("*.jar"))]))
    sources=[mcp/"src/minecraft/net/minecraft"/path for path in ("potion/PotionHelper.java","potion/PotionEffect.java","item/ItemPotion.java")]
    run(["javac","-encoding","UTF-8","--release","8","-cp",classpath,"-d",str(classes),*map(str,sources),str(root/"tests/java/SimulationExport.java")],build)
    raw=build/"brewing.json";run(["java","-Djava.awt.headless=true","-cp",classpath,"SimulationExport",str(raw)],build);data=json.loads(raw.read_text(encoding="utf-8"))
    lines=["#pragma once","// Generated by tools/export_simulation.py from original MCP potion/item behavior.","#include <array>","#include <cstdint>","namespace mc::brewing::data {","struct Ingredient { int item; std::uint16_t mask; const char* formula; };",f"inline constexpr std::array<Ingredient,{len(data['ingredients'])}> ingredients{{{{"]
    for value in data["ingredients"]:lines.append("    {"+str(value["item"])+","+str(value["mask"])+","+json.dumps(value["formula"])+"},")
    lines +=["}};","inline constexpr std::array<std::uint16_t,32768> effects{{"]
    for offset in range(0,32768,64):lines.append("    "+",".join(map(str,data["effect_groups"][offset:offset+64]))+",")
    lines +=["}};","} // namespace mc::brewing::data",""]
    output=root/"include/mc/brewing_data.hpp";output.write_text("\n".join(lines),encoding="ascii")
    report={"ingredient_rules":len(data["ingredients"]),"potion_metadata_values":32768,"effect_groups":data["unique_nonempty_effect_groups"],"header_sha256":hashlib.sha256(output.read_bytes()).hexdigest(),"source_sha256":{str(path.relative_to(mcp)):hashlib.sha256(path.read_bytes()).hexdigest() for path in sources}}
    (build/"report.json").write_text(json.dumps(report,indent=2),encoding="utf-8");print(json.dumps(report,indent=2))
if __name__=="__main__":main()
