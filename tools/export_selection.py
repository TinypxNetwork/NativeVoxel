#!/usr/bin/env python3
"""Export original metadata-dependent selection/ray bounds from MCP getters."""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import sys
from export_registry import javac
from verify_physics import make_reference,run


def main() -> None:
    root=Path(__file__).resolve().parents[1];parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mcp",type=Path,default=root.parent/"MCP-919-main");args=parser.parse_args();mcp=args.mcp.resolve()
    build=root/"build/selection_reference";build.mkdir(parents=True,exist_ok=True);make_reference(root,mcp,build)
    cp=os.pathsep.join(str(p) for p in [build,root/"build/physics_reference/oracle_classes",mcp/"bin/minecraft",mcp/"jars/versions/1.8.9/1.8.9.jar",*sorted((mcp/"jars/libraries").rglob("*.jar"))])
    source=mcp/"src/minecraft/net/minecraft"
    javac(["-encoding","UTF-8","--release","8","-cp",cp,"-d",str(build),
           *map(str,sorted((source/"block").rglob("*.java"))),str(build/"PhysicsReference.java"),str(root/"tests/java/SelectionExport.java")],build)
    raw=build/"selection.json";run(["java","-Djava.awt.headless=true","-cp",cp,"SelectionExport",str(raw)],build)
    records=json.loads(raw.read_text());shapes=[];lookup={};indices=[]
    for record in records:
        key=(tuple(record.get("rayBounds",[0,0,0,1,1,1])),tuple(record.get("selected",[0,0,0,1,1,1])),
             record.get("ray",False),record.get("liquidRay",False),record.get("collision",False),record["valid"])
        if key not in lookup:lookup[key]=len(shapes);shapes.append(key)
        indices.append(lookup[key])
    out=["#pragma once","// Generated by tools/export_selection.py from original Java block methods.","#include <array>","#include <cstdint>","namespace mc::selection {",
         "struct Shape { std::array<double,6> rayBounds,selected; bool ray,liquidRay,collision,valid; };",f"inline constexpr std::array<Shape,{len(shapes)}> shapes{{{{"]
    for ray,selected,can,liquid,collision,valid in shapes:
        nums=lambda values:",".join(repr(float(x)) for x in values)
        out.append("    {{{"+nums(ray)+"}},{{"+nums(selected)+"}},"+",".join(str(b).lower() for b in [can,liquid,collision,valid])+"},")
    out += ["}};",f"inline constexpr std::array<std::uint16_t,{len(indices)}> index{{{{"]
    for i in range(0,len(indices),32):out.append("    "+",".join(str(x) for x in indices[i:i+32])+",")
    out += ["}};","inline const Shape& state(unsigned value){return shapes[value<index.size()?index[value]:index[0]];}","} // namespace mc::selection",""]
    (root/"include/mc/selection_data.hpp").write_text("\n".join(out),encoding="ascii")
    print(f"Exported {len(indices)} vanilla block states into {len(shapes)} distinct ray/selection records")


if __name__=="__main__":
    try:main()
    except Exception as error:print(f"Selection export failed: {error}",file=sys.stderr);sys.exit(1)
